import { expect, test } from "./fakeTurnstile";
import plan from "../fixtures/plan.json";

// The real API is never called: /api/estimate is intercepted in every test.

test("happy path shows both tabs", async ({ page }) => {
  await page.route("**/api/estimate", (route) => route.fulfill({ json: plan }));
  await page.goto("/");
  await page.getByLabel("Feature description").fill("Add one-time code login with email delivery and rate limiting");
  const submit = page.getByRole("button", { name: "Estimate this feature" });
  await expect(submit).toBeEnabled(); // enabled once the fake Turnstile token arrives
  await submit.click();

  await expect(page.getByRole("heading", { name: plan.scope.title })).toBeVisible();
  await page.getByRole("tab", { name: "Tasks" }).click();
  await expect(page.getByRole("cell", { name: /OTP generate and verify endpoints/ })).toBeVisible();
});

test("rate limit shows the server message", async ({ page }) => {
  await page.route("**/api/estimate", (route) =>
    route.fulfill({ status: 429, json: { error: "You've used 10 estimates this hour. The button shows when you can try again." } }),
  );
  await page.goto("/");
  await page.getByLabel("Feature description").fill("Add one-time code login with email delivery and rate limiting");
  const submit = page.getByRole("button", { name: "Estimate this feature" });
  await expect(submit).toBeEnabled({ timeout: 15_000 });
  await submit.click();
  // Filter by text: Next.js also renders an empty role="alert" route announcer.
  await expect(page.getByRole("alert").filter({ hasText: "estimates this hour" })).toBeVisible();
});

test("an unchanged example chip shows its saved plan at once, with no request (E5)", async ({ page }) => {
  let calls = 0;
  await page.route("**/api/estimate", (route) => {
    calls += 1;
    return route.fulfill({ json: plan });
  });
  await page.goto("/");
  await page.getByRole("group", { name: "Example features" }).getByRole("button").first().click();
  await page.getByRole("button", { name: "Estimate this feature" }).click();
  await expect(page.getByText(/^Saved plan for this example, generated by Claude on \d{4}-\d{2}-\d{2}\./)).toBeVisible();
  await expect(page.getByTestId("answer")).toHaveText(/^About \d+ weeks? for a 4-person team, roughly RM [\dk]+–[\dk]+ to build\.$/);
  // A different team size is a new request.
  await page.getByRole("slider", { name: "Team size" }).press("ArrowRight");
  const submit = page.getByRole("button", { name: "Estimate this feature" });
  await expect(submit).toBeEnabled({ timeout: 15_000 });
  await submit.click();
  await expect(page.getByText(plan.scope.title, { exact: true }).first()).toBeVisible();
  expect(calls).toBe(1);
});

test("on phones the four lists start closed and open on tap (E9), and every card shows fact dots (G3)", async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 });
  await page.route("**/api/estimate", (route) => route.fulfill({ json: plan }));
  await page.goto("/");
  await page.getByLabel("Feature description").fill("Add one-time code login with email delivery and rate limiting");
  const submit = page.getByRole("button", { name: "Estimate this feature" });
  await expect(submit).toBeEnabled({ timeout: 15_000 });
  await submit.click();
  const risks = page.getByRole("region", { name: "Risks" });
  await expect(risks.getByRole("listitem").first()).toBeHidden();
  await risks.locator("summary").click();
  await expect(risks.getByRole("listitem").first()).toBeVisible();
  const dots = page.getByTestId("fact-dots").locator("i");
  await expect(dots).toHaveCount(6);
  await expect(page.getByTestId("fact-dots").locator("i[data-on]")).toHaveCount(Object.values(plan.scope.facts).filter(Boolean).length);
});

test("budget charts match the tables (G2)", async ({ page }) => {
  await page.goto("/");
  await page.getByRole("tab", { name: "Budget" }).click();
  const table = page.getByTestId("budget");
  const build = (await table.getByRole("row", { name: /Estimated build cost/ }).getByRole("cell").last().textContent())!.trim();
  // Compare text, not accessible names: money uses a no-break space that names normalise.
  await expect(page.locator(".bchart__heading")).toHaveText(`Where the build money goes: ${build}`);
  await expect(page.locator(".bchart__legend li")).toHaveCount(await page.getByTestId("build-bar").locator("span").count());
  const cmp = page.getByTestId("compare");
  const total = async (i: number) => (await cmp.getByRole("row", { name: /Build total/ }).getByRole("cell").nth(i).textContent())!.trim();
  const label = await page.getByTestId("compare-bars").getAttribute("aria-label");
  expect(label).toBe(`Build total range. Traditional: ${await total(0)}. With AI agents: ${await total(1)}.`);
});
