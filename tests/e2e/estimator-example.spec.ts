import { expect, test } from "./fakeTurnstile";
import plan from "../fixtures/plan.json";
import { estimatorCopy, estimatorExamples } from "../../lib/content";
import { samplePlan } from "../../lib/samplePlan";

// The example plan is stored in the page: showing it must never call /api/estimate.

test("on load the stored example is shown, labelled, with no request and no focus move", async ({ page }) => {
  const calls: string[] = [];
  await page.route("**/api/estimate", (route) => {
    calls.push(route.request().url());
    return route.abort();
  });
  await page.goto("/");

  const heading = page.getByRole("heading", { name: samplePlan.title });
  await expect(heading).toBeVisible();
  await expect(heading).not.toBeFocused();
  await expect(page.getByText(estimatorCopy.example.note(estimatorExamples[0]))).toBeVisible();
  // Focus skips past the line above the heading, so a screen reader must get it as the description.
  await expect(heading).toHaveAccessibleDescription(estimatorCopy.example.note(estimatorExamples[0]));
  await expect(page.getByText(estimatorCopy.example.footer)).toBeVisible();
  // The example is hand-written, so the "generated by Claude" footer must not sit under it.
  await expect(page.getByText(estimatorCopy.footerNote)).toHaveCount(0);

  await page.getByRole("tab", { name: estimatorCopy.tabTasks }).click();
  await expect(page.getByRole("tabpanel", { name: estimatorCopy.tabTasks })).toContainText(samplePlan.phases[0].tasks[0].task);
  expect(calls).toEqual([]);
});

test("a live estimate replaces the example and its labels", async ({ page }) => {
  const live = { scope: { ...plan.scope, title: "Live plan title" } };
  await page.route("**/api/estimate", (route) => route.fulfill({ json: live }));
  await page.goto("/");
  await expect(page.getByText(estimatorCopy.example.footer)).toBeVisible();

  await page.getByLabel("Feature description").fill("Add one-time code login with email delivery and rate limiting");
  const submit = page.getByRole("button", { name: estimatorCopy.submit });
  await expect(submit).toBeEnabled();
  await submit.click();

  await expect(page.getByRole("heading", { name: "Live plan title" })).toBeFocused();
  await expect(page.getByRole("heading", { name: "Live plan title" })).toHaveAccessibleDescription("");
  await expect(page.getByText(estimatorCopy.footerNote)).toBeVisible();
  await expect(page.getByText(estimatorCopy.example.footer)).toHaveCount(0);
  await expect(page.getByText(estimatorCopy.example.note(estimatorExamples[0]))).toHaveCount(0);
});

test.describe("tap targets on a phone", () => {
  test.use({ viewport: { width: 390, height: 844 }, hasTouch: true });

  test("links and buttons a thumb must hit are at least 44px tall", async ({ page }) => {
    await page.goto("/");
    // The random chips replace the server-rendered ones after hydration; measuring mid-swap reads detached
    // nodes as 0px tall.
    await expect(page.getByRole("group", { name: "Example features" })).toHaveAttribute("data-ready", "");
    const short = await page
      .locator(".hero__actions a, .project__links a, .contact__links a, .contact__primary a, .theme-toggle, .estimator__chip, .estimator__lock > button[type=submit]")
      .evaluateAll((els) =>
        els
          .map((el) => ({ name: (el.textContent || el.getAttribute("aria-label") || "").trim().slice(0, 30), h: Math.round(el.getBoundingClientRect().height * 10) / 10 }))
          .filter((t) => t.h < 44),
      );
    expect(short).toEqual([]);
  });
});

test("after a field error, typing brings the example back instead of an empty results area", async ({ page }) => {
  const message = "Describe the feature in at least 20 characters.";
  await page.route("**/api/estimate", (route) => route.fulfill({ status: 400, json: { error: message } }));
  await page.goto("/");
  const field = page.getByLabel("Feature description");
  await field.fill("Add one-time code login with email delivery and rate limiting");
  const submit = page.getByRole("button", { name: estimatorCopy.submit });
  await expect(submit).toBeEnabled();
  await submit.click();
  await expect(page.getByText(message)).toBeVisible();

  await field.press("End");
  await field.pressSequentially(" now");
  await expect(page.getByText(message)).toHaveCount(0);
  await expect(page.getByRole("heading", { name: samplePlan.title })).toBeVisible();
  // Focus stays in the field, so no typed character is lost.
  await expect(field).toBeFocused();
  await expect(field).toHaveValue("Add one-time code login with email delivery and rate limiting now");
});

test.describe("example preview on a phone", () => {
  test.use({ viewport: { width: 390, height: 844 } });

  test("a link above the form jumps to the example plan, and goes away with a live estimate", async ({ page }) => {
    await page.route("**/api/estimate", (route) => route.fulfill({ json: { scope: { ...plan.scope, title: "Live plan title" } } }));
    await page.goto("/");
    const preview = page.getByRole("link", { name: /^See an example plan below/ });
    await expect(preview).toContainText(samplePlan.title);
    await preview.click();
    await expect(page.getByRole("heading", { name: samplePlan.title })).toBeInViewport();

    await page.getByLabel("Feature description").fill("Add one-time code login with email delivery and rate limiting");
    await page.getByRole("button", { name: estimatorCopy.submit }).click();
    await expect(page.getByRole("heading", { name: "Live plan title" })).toBeVisible();
    await expect(preview).toHaveCount(0);
  });
});

